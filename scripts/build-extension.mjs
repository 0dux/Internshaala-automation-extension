import { readFile, writeFile, access } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(root, 'internshala-filter-saver.user.js');
const extensionDir = path.join(root, 'chrome-extension');
const contentPath = path.join(extensionDir, 'content.js');
const manifestPath = path.join(extensionDir, 'manifest.json');

const source = await readFile(sourcePath, 'utf8');
const header = source.match(/^\/\/ ==UserScript==[\s\S]*?\/\/ ==\/UserScript==\r?\n/);

if (!header) {
  throw new Error('Could not find the Tampermonkey header in the userscript.');
}

const version = source.match(/^\/\/ @version\s+(\S+)/m)?.[1];
if (!version) {
  throw new Error('Could not read @version from the userscript.');
}

const body = source.slice(header[0].length).replace(/^\s*\r?\n/, '');
const banner =
  '/**\n' +
  ` * Internshala Saved Filters ${version} - Chrome extension content script\n` +
  ' * Generated from internshala-filter-saver.user.js by scripts/build-extension.mjs.\n' +
  ' * Do not edit this file directly; edit the userscript and run `npm.cmd run build`.\n' +
  ' */\n\n';

await writeFile(contentPath, banner + body, 'utf8');

const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
manifest.version = version;
await writeFile(manifestPath, JSON.stringify(manifest, null, 2) + '\n', 'utf8');

const packagePath = path.join(root, 'package.json');
const packageJson = JSON.parse(await readFile(packagePath, 'utf8'));
packageJson.version = version;
await writeFile(packagePath, JSON.stringify(packageJson, null, 2) + '\n', 'utf8');

for (const size of Object.keys(manifest.icons)) {
  await access(path.join(extensionDir, manifest.icons[size]));
}

console.log(`Built chrome-extension/content.js from userscript v${version}.`);
console.log(`Manifest and package versions: ${manifest.version}`);
